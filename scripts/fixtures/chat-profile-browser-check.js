(async () => {
const c = window.__roomPerf, checks = [];
const assert = (ok,label) => {if(!ok)throw new Error(label);checks.push(label);};
const wait = async f => {const end=Date.now()+6000;while(!f()){if(Date.now()>end)throw new Error("Condition timed out");await new Promise(r=>setTimeout(r,25));}};
const node = id => document.querySelector('[data-message-id="'+id+'"]');
const row = (author,body) => ({id:crypto.randomUUID(),session_id:'11111111-1111-4111-8111-111111111111',user_id:author,body,scope:'general',dm_peer_user_id:null,created_at:new Date().toISOString()});
const reads = id => c.requests.filter(r=>r.table==='profiles'&&r.filters.some(([field,ids])=>field==='id'&&(Array.isArray(ids)?ids:[ids]).includes(id))).length;
if (!c) throw new Error('Open the isolated room-performance fixture, not production');
await wait(()=>document.querySelector('[data-message-id]')?.innerText.includes('Host Name'));
assert(document.querySelector('[data-message-id]').innerText.includes('Host Name'),'partial host override does not block real name');
const created=c.createdChannels;c.profileDelay=350;
const a=crypto.randomUUID(),one=row(a,'Delayed name one'),two=row(a,'Delayed name two');
c.emit('session_chat_messages','INSERT',one);c.emit('session_chat_messages','INSERT',two);
assert(!node(one.id)&&!node(two.id),'messages wait for author profile');
await wait(()=>node(one.id)&&node(two.id));
assert(node(one.id).innerText.includes('Member '+a)&&node(two.id).innerText.includes('Member '+a),'both messages render real sender name');
assert(reads(a)===1,'parallel messages share one profile SELECT');
assert(node(one.id).querySelector('img').src.startsWith('data:image/'),'real avatar URL is attached');
const b=crypto.randomUUID(),transient=row(b,'Transient failure');
c.profileFailures[b]=1;c.emit('session_chat_messages','INSERT',transient);await wait(()=>node(transient.id));
assert(node(transient.id).innerText.includes('Member '+b)&&reads(b)===2,'one automatic retry recovers name and avatar');
const d=crypto.randomUUID(),failed=row(d,'Persistent failure');
c.profileFailures[d]=2;c.emit('session_chat_messages','INSERT',failed);
await wait(()=>document.querySelector('[role="status"]'));
assert(reads(d)===2,'persistent failure is bounded, no polling');
document.querySelector('[role="status"] button').click();
await wait(()=>node(failed.id)?.innerText.includes('Member '+d));
assert(!document.querySelector('[role="status"]')&&reads(d)===3,'Retry profiles replaces placeholder with actual name');
assert(node(failed.id).querySelector('img').src.startsWith('data:image/'),'retry updates memoized message avatar');
const e=crypto.randomUUID(),deleted=row(e,'Never resurrect this');
c.emit('session_chat_messages','INSERT',deleted);await wait(()=>reads(e)>0);
c.emit('session_chat_messages','DELETE',deleted);await new Promise(r=>setTimeout(r,500));
assert(!node(deleted.id),'delete during profile fetch cannot resurrect message');
const f=crypto.randomUUID(),edited=row(f,'Old text');
c.emit('session_chat_messages','INSERT',edited);await wait(()=>reads(f)>0);
c.emit('session_chat_messages','UPDATE',{...edited,body:'New text'});await wait(()=>node(edited.id));
assert(node(edited.id).innerText.includes('New text')&&!node(edited.id).innerText.includes('Old text'),'newer UPDATE wins while author profile is pending');
assert(reads(f)===1,'pending UPDATE shares author read');
c.delayNextRead=650;c.reconnect();
const g=crypto.randomUUID(),newer=row(g,'Newer than snapshot');
c.emit('session_chat_messages','INSERT',newer);await wait(()=>node(newer.id));await new Promise(r=>setTimeout(r,750));
assert(!!node(newer.id),'stale reconnect SELECT cannot remove new profiled message');
const h=crypto.randomUUID(),wrongView=row(h,'Do not leak to DM');
c.emit('session_chat_messages','INSERT',wrongView);await wait(()=>reads(h)>0);
[...document.querySelectorAll('nav button')].find(b=>b.textContent==='Direct chat').click();await new Promise(r=>setTimeout(r,550));
assert(!node(wrongView.id),'pending author load cannot leak into another thread');
assert(c.createdChannels===created,'profile updates and thread switches do not recreate channels');
assert(window.__consoleErrors.length===0,'no browser runtime errors');
c.unmount();await wait(()=>c.channels.length===0);
assert(c.channels.length===0,'all realtime channels removed on unmount');
window.__chatProfileResults=checks;return checks;
})()
